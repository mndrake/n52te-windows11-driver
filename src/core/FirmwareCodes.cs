        private static Dictionary<string, byte> byName;

        public static bool IsMouse(int code) { return code >= 0xD0 && code <= 0xD8; }
        public static bool IsKeymapSwitch(int code) { return code >= 0xD9 && code <= 0xDF; }
        public static bool IsCommand(int code) { return code >= 0xC0 && code <= 0xCE; }
        public static bool IsMedia(int code) { return code >= 0xE8 && code <= 0xFF; }

        public static string Name(int code)
        {
            string n;
            return names.TryGetValue(code, out n) ? n : string.Format("0x{0:X2}", code);
        }

        private static string Normalize(string s)
        {
            var chars = new List<char>();
            foreach (char c in s.ToLowerInvariant()) if (c != ' ' && c != '_') chars.Add(c);
            return new string(chars.ToArray());
        }

        // A code by name ("H", "L Shift", "lshift", "Mouse Left", "Scroll Up") or as hex ("0x35").
        public static bool TryParse(string token, out byte code)
        {
            code = 0;
            if (token.StartsWith("0x", StringComparison.OrdinalIgnoreCase))
            {
                int v;
                if (!int.TryParse(token.Substring(2), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out v) || v < 0 || v > 0xFF) return false;
                code = (byte)v;
                return true;
            }
            if (byName == null)
            {
                var d = new Dictionary<string, byte>();
                foreach (var kv in names) d[Normalize(kv.Value)] = (byte)kv.Key;
                d["shift"] = LeftShift; d["ctrl"] = LeftCtrl; d["alt"] = LeftAlt;
                d["space"] = 0x57; d["escape"] = 0x15; d["return"] = 0x56;
                byName = d;
            }
            return byName.TryGetValue(Normalize(token), out code);
        }

        // Windows virtual-key code -> firmware code, from the recorder table in n52teCfg.exe
        // (0x48cbb0, docs/reverse-engineering/07). 0 = the keypad has no such key.
        public static byte FromVirtualKey(int vk)
        {
            byte code;
            return vkTable.TryGetValue(vk, out code) ? code : (byte)0;
        }

