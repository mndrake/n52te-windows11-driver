namespace N52te;

/// <summary>Maps Windows virtual-key codes to firmware key codes (for the macro recorder).</summary>
public static class WindowsKeys
{
    private static readonly Dictionary<int, byte> VkToFirmware = Build();

    private static Dictionary<int, byte> Build()
    {
        var map = new Dictionary<int, byte>();
        byte[] letters = { 0x14, 0x2F, 0x26, 0x24, 0x22, 0x2C, 0x2D, 0x35, 0x3A, 0x34, 0x3C, 0x44, 0x36,
                           0x37, 0x42, 0x4A, 0x12, 0x2A, 0x1C, 0x2B, 0x32, 0x2E, 0x1A, 0x1E, 0x33, 0x16 };
        for (int i = 0; i < 26; i++) map[0x41 + i] = letters[i];
        byte[] digits = { 0x49, 0x11, 0x19, 0x21, 0x29, 0x28, 0x30, 0x31, 0x39, 0x41 };
        for (int i = 0; i < 10; i++) map[0x30 + i] = digits[i];
        byte[] fkeys = { 0x18, 0x20, 0x23, 0x25, 0x55, 0x3D, 0x43, 0x40, 0x50, 0x51, 0x61, 0x59 };
        for (int i = 0; i < 12; i++) map[0x70 + i] = fkeys[i];
        byte[] numpad = { 0x5D, 0x64, 0x5C, 0x6C, 0x63, 0x5B, 0x6B, 0x62, 0x5A, 0x6A };
        for (int i = 0; i < 10; i++) map[0x60 + i] = numpad[i];

        void Add(int vk, byte code) => map[vk] = code;
        Add(0x08, 0x53); Add(0x09, 0x13); Add(0x0D, 0x56); Add(0x13, 0x76); Add(0x14, 0x1B); Add(0x1B, 0x15);
        Add(0x20, 0x57); Add(0x21, 0x68); Add(0x22, 0x69); Add(0x23, 0x71); Add(0x24, 0x70);
        Add(0x25, 0x77); Add(0x26, 0x75); Add(0x27, 0x5F); Add(0x28, 0x67); Add(0x2C, 0x7A); Add(0x2D, 0x58); Add(0x2E, 0x60);
        Add(0x5B, 0x9C); Add(0x5C, 0x9C); Add(0x5D, 0x9A);
        Add(0x6A, 0x6E); Add(0x6B, 0x72); Add(0x6D, 0x6F); Add(0x6E, 0x6D); Add(0x6F, 0x5E);
        Add(0x90, 0x66); Add(0x91, 0x79);
        Add(0xA0, 0x83); Add(0xA1, 0x86); Add(0xA2, 0x88); Add(0xA3, 0x8E); Add(0xA4, 0x7D); Add(0xA5, 0x7F);
        // Generic Shift/Ctrl/Alt (WinForms reports these) map to the left-hand keys.
        Add(0x10, 0x83); Add(0x11, 0x88); Add(0x12, 0x7D);
        Add(0xAD, 0xED); Add(0xAE, 0xEF); Add(0xAF, 0xEE); Add(0xB0, 0xE8); Add(0xB1, 0xE9); Add(0xB2, 0xEA); Add(0xB3, 0xEC);
        Add(0xBA, 0x4C); Add(0xBB, 0x38); Add(0xBC, 0x3E); Add(0xBD, 0x48); Add(0xBE, 0x46); Add(0xBF, 0x4F);
        Add(0xC0, 0x10); Add(0xDB, 0x4B); Add(0xDC, 0x54); Add(0xDD, 0x3B); Add(0xDE, 0x4D); Add(0xE2, 0x4E);
        return map;
    }

    public static byte? ToFirmware(int virtualKey) => VkToFirmware.TryGetValue(virtualKey, out var code) ? code : null;

    public static IEnumerable<int> MappedVirtualKeys => VkToFirmware.Keys;
}

/// <summary>Where the Editor and Companion keep shared files.</summary>
public static class AppPaths
{
    public static string DataFolder =>
        Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData), "n52te");

    /// <summary>The profile the Companion follows (written by the Editor).</summary>
    public static string ActiveProfile => Path.Combine(DataFolder, "active-profile.json");

    public static string ProfilesFolder => Path.Combine(DataFolder, "Profiles");

    public static void WriteActiveProfile(Profile profile)
    {
        Directory.CreateDirectory(DataFolder);
        var temp = ActiveProfile + ".tmp";
        File.WriteAllText(temp, ProfileJson.Serialize(profile));
        File.Move(temp, ActiveProfile, overwrite: true);
    }
}
